export const enToEs = Object.fromEntries(Object.entries(esToEn).map(([es, en]) => [en, es]));

export function translateText(value, lang) {
  if (!value || typeof value !== "string") return value;

  if (lang === "en" && enToEs[value]) return value;
  if (lang === "es" && esToEn[value]) return value;

  const source = lang === "en" ? esToEn : enToEs;
  let out = value;

  if (source[out]) return source[out];

  const trimmed = out.trim();
  if (source[trimmed]) return out.replace(trimmed, source[trimmed]);

  for (const [from, to] of Object.entries(source).sort((a, b) => b[0].length - a[0].length)) {
    if (out.includes(from)) out = out.split(from).join(to);
  }

  if (lang === "en") {
    out = out.replace(/(\d+) seleccionada(s?)\./g, (_, n) => `${n} selected.`);
    out = out.replace(/Media:/g, "Average:");
    out = out.replace(/kcal hoy/g, "kcal today");
    out = out.replace(/Alimento #(\d+)/g, "Food #$1");
    out = out.replace(/¿Borrar "([^"]+)"\?/g, 'Delete "$1"?');
  } else {
    out = out.replace(/(\d+) selected\./g, (_, n) => `${n} seleccionada${n === "1" ? "" : "s"}.`);
    out = out.replace(/Average:/g, "Media:");
    out = out.replace(/kcal today/g, "kcal hoy");
    out = out.replace(/Food #(\d+)/g, "Alimento #$1");
    out = out.replace(/Delete "([^"]+)"\?/g, '¿Borrar "$1"?');
  }

  return out;
}
